"""Regenerate the compiled catalog. Normal Visual Studio builds need no Python."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
rows = json.loads((root / 'resources/translations.json').read_text(encoding='utf-8'))
seen = set()
lines = ['// Generated by tools/generate_translations.py; edit resources/translations.json.']
for row in rows:
    assert set(row) == {'tr', 'en', 'zh-CN'}, 'Invalid language columns'
    assert row['tr'] not in seen, 'Duplicate translation key'
    assert all(isinstance(value, str) and value for value in row.values()), 'Empty translation'
    seen.add(row['tr'])
    lines.append('    {' + ', '.join('L' + json.dumps(row[code], ensure_ascii=False) for code in ('tr', 'en', 'zh-CN')) + '},')
(root / 'src/translations.inc').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Generated {len(rows)} translations.')
